"""
train.py - Base model vs. LoRA fine-tuned model for AI-text detection.

Steps:
  1. Load the data and make the fixed 80/20 split (preprocess.py).
  2. BASE MODEL: ask Qwen2.5-1.5B-Instruct (no training) whether each test
     text was written by a Human or an AI, and evaluate the answers.
  3. FINE-TUNE: train small LoRA adapters on the training set (the 1.5B
     original weights stay frozen).
  4. FINE-TUNED MODEL: ask the same question on the same test texts.
  5. Save results.json, test_predictions.csv and the LoRA adapter.

How we get a probability:
  The prompt ends with "Answer with one word: Human or AI." We look at the
  model's score for the next word being "Human" and the score for "AI",
  and turn those two scores into P(AI) with a softmax.
  Fine-tuning trains exactly this: cross-entropy on those two scores.

Kaggle (GPU T4/P100, Internet ON):
    python src/train.py --data /kaggle/input/<dataset>/<file>.csv --max-rows 10000
Quick test:
    python src/train.py --data data/sample.csv --max-rows 2000 --epochs 1
"""

import argparse
import json
import os
import time

import numpy as np
import torch
from peft import LoraConfig, get_peft_model
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score,
                             precision_score, recall_score, roc_auc_score)
from transformers import (AutoModelForCausalLM, AutoTokenizer,
                          get_linear_schedule_with_warmup)

from preprocess import SEED, load_data, split_data

MODEL_NAME = "Qwen/Qwen2.5-1.5B-Instruct"

PROMPT = ("Read the text below and decide whether it was written by a human "
          "or generated by an AI model.\n\n"
          "Text: {text}\n\n"
          "Answer with one word: Human or AI.")


# ---------------------------------------------------------------------------
# Model helpers (also used by predict.py)
# ---------------------------------------------------------------------------

def get_device():
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_model(model_name, device):
    """Load the tokenizer and the base model.
    float16 on the GPU (half the memory, about 2x faster on T4/P100)."""
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    tokenizer.padding_side = "left"      # so the LAST position is the real end of every prompt
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    dtype = torch.float16 if device == "cuda" else torch.float32
    model = AutoModelForCausalLM.from_pretrained(model_name, torch_dtype=dtype)
    model.to(device)
    return tokenizer, model


def answer_token_ids(tokenizer):
    """Token ids of the two possible answers: 'Human' (class 0) and 'AI' (class 1)."""
    human_id = tokenizer.encode("Human", add_special_tokens=False)[0]
    ai_id = tokenizer.encode("AI", add_special_tokens=False)[0]
    return [human_id, ai_id]


def make_prompts(tokenizer, texts, max_len):
    """Cut each text to max_len tokens, put it in the prompt and apply the chat format.
    The text is cut BEFORE building the prompt, so the question is never cut off."""
    prompts = []
    for text in texts:
        ids = tokenizer.encode(text, add_special_tokens=False)[:max_len]
        short_text = tokenizer.decode(ids)
        messages = [{"role": "user", "content": PROMPT.format(text=short_text)}]
        prompts.append(tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True))
    return prompts


def answer_logits(model, tokenizer, prompts, device):
    """Return a (batch, 2) tensor: the model's scores for 'Human' and 'AI'
    as the next word after each prompt."""
    enc = tokenizer(prompts, return_tensors="pt", padding=True).to(device)

    # Works for the plain model and for the LoRA (PEFT) model.
    lm = model.get_base_model() if hasattr(model, "get_base_model") else model

    # Run the transformer layers, keep only the last position of each prompt,
    # and compute scores for just our 2 answer words (instead of the whole
    # 150k-word vocabulary, which would use a lot of GPU memory).
    hidden = lm.model(input_ids=enc["input_ids"],
                      attention_mask=enc["attention_mask"]).last_hidden_state[:, -1, :]
    answer_weights = lm.lm_head.weight[answer_token_ids(tokenizer)]   # (2, hidden_size)
    return hidden @ answer_weights.T                                 # (batch, 2)


@torch.no_grad()
def predict_ai_prob(model, tokenizer, texts, max_len, batch_size, device):
    """P(AI) for every text."""
    model.eval()
    probs = []
    for i in range(0, len(texts), batch_size):
        prompts = make_prompts(tokenizer, texts[i:i + batch_size], max_len)
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=(device == "cuda")):
            logits = answer_logits(model, tokenizer, prompts, device)
        probs.extend(torch.softmax(logits.float(), dim=-1)[:, 1].tolist())
    return np.array(probs)


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def evaluate(y_true, ai_probs):
    """Standard metrics. AI (label 1) is the positive class."""
    y_pred = (ai_probs >= 0.5).astype(int)
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "f1": f1_score(y_true, y_pred, zero_division=0),
        "roc_auc": roc_auc_score(y_true, ai_probs),
        # [[TN, FP], [FN, TP]]  (rows = true label, columns = predicted label)
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=[0, 1]).tolist(),
    }


def print_comparison(results):
    names = [n for n in ["base", "finetuned"] if n in results]
    print("\n" + "=" * 46)
    print(f"{'metric':<12}" + "".join(f"{n:>17}" for n in names))
    print("-" * 46)
    for metric in ["accuracy", "precision", "recall", "f1", "roc_auc", "seconds"]:
        row = f"{metric:<12}"
        for n in names:
            value = results[n].get(metric)
            row += f"{value:>17.4f}" if value is not None else f"{'-':>17}"
        print(row)
    print("=" * 46)
    for n in names:
        (tn, fp), (fn, tp) = results[n]["confusion_matrix"]
        print(f"{n}: TN={tn} FP={fp} FN={fn} TP={tp}")


# ---------------------------------------------------------------------------
# Fine-tuning with LoRA
# ---------------------------------------------------------------------------

def add_lora(model, r):
    """Freeze the 1.5B original weights and add small trainable LoRA matrices
    to the attention layers."""
    config = LoraConfig(
        r=r,                       # rank of the LoRA matrices
        lora_alpha=2 * r,          # scaling factor
        lora_dropout=0.05,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
        task_type="CAUSAL_LM",
    )
    model = get_peft_model(model, config)
    model.print_trainable_parameters()
    return model


def finetune(model, tokenizer, train_df, args, device):
    model.config.use_cache = False
    model.gradient_checkpointing_enable()     # saves GPU memory (slightly slower)
    model.enable_input_require_grads()        # needed for gradient checkpointing + LoRA
    model = add_lora(model, args.lora_r)

    texts = train_df["text"].tolist()
    labels = torch.tensor(train_df["label"].values)
    steps_per_epoch = (len(texts) + args.batch_size - 1) // args.batch_size
    total_steps = steps_per_epoch * args.epochs

    trainable = [p for p in model.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(trainable, lr=args.lr, weight_decay=0.01)
    scheduler = get_linear_schedule_with_warmup(optimizer, int(0.1 * total_steps), total_steps)
    scaler = torch.amp.GradScaler("cuda", enabled=(device == "cuda"))
    loss_fn = torch.nn.CrossEntropyLoss()

    rng = np.random.default_rng(SEED)
    step = 0
    for epoch in range(args.epochs):
        model.train()
        order = rng.permutation(len(texts))      # shuffle each epoch
        for start in range(0, len(texts), args.batch_size):
            idx = order[start:start + args.batch_size]
            prompts = make_prompts(tokenizer, [texts[i] for i in idx], args.max_len)
            y = labels[idx].to(device)

            with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=(device == "cuda")):
                logits = answer_logits(model, tokenizer, prompts, device)
            loss = loss_fn(logits.float(), y)

            optimizer.zero_grad()
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(trainable, 1.0)
            scaler.step(optimizer)
            scaler.update()
            scheduler.step()

            step += 1
            if step % 50 == 0 or step == total_steps:
                print(f"epoch {epoch + 1}  step {step}/{total_steps}  loss {loss.item():.4f}")
    return model


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="data/sample.csv")
    parser.add_argument("--out", default="outputs")
    parser.add_argument("--model-name", default=MODEL_NAME)
    parser.add_argument("--max-rows", type=int, default=None)
    parser.add_argument("--epochs", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--max-len", type=int, default=256, help="max tokens of each text")
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--lora-r", type=int, default=16)
    args = parser.parse_args()

    torch.manual_seed(SEED)
    os.makedirs(args.out, exist_ok=True)
    device = get_device()
    print(f"Device: {device}   Model: {args.model_name}")

    # 1. Data
    df = load_data(args.data, args.max_rows)
    train_df, test_df = split_data(df)
    print(f"Train: {len(train_df)}   Test: {len(test_df)}")
    y_test = test_df["label"].values
    test_texts = test_df["text"].tolist()

    tokenizer, model = load_model(args.model_name, device)
    results = {"settings": vars(args)}

    # 2. Base model (no training)
    print("\nEvaluating the BASE model (zero-shot)...")
    t0 = time.time()
    base_probs = predict_ai_prob(model, tokenizer, test_texts, args.max_len, args.batch_size * 2, device)
    results["base"] = evaluate(y_test, base_probs)
    results["base"]["seconds"] = time.time() - t0

    # 3. Fine-tune with LoRA
    print("\nFine-tuning with LoRA...")
    t0 = time.time()
    model = finetune(model, tokenizer, train_df, args, device)
    train_seconds = time.time() - t0
    model.save_pretrained(os.path.join(args.out, "lora_adapter"))
    tokenizer.save_pretrained(os.path.join(args.out, "lora_adapter"))

    # 4. Fine-tuned model
    print("\nEvaluating the FINE-TUNED model...")
    t0 = time.time()
    ft_probs = predict_ai_prob(model, tokenizer, test_texts, args.max_len, args.batch_size * 2, device)
    results["finetuned"] = evaluate(y_test, ft_probs)
    results["finetuned"]["seconds"] = time.time() - t0
    results["finetuned"]["training_seconds"] = train_seconds

    # 5. Save everything
    with open(os.path.join(args.out, "results.json"), "w") as f:
        json.dump(results, f, indent=2)

    # Every test text with both models' P(AI): used for the
    # false positive / false negative analysis in the report.
    test_df["base_ai_prob"] = base_probs
    test_df["finetuned_ai_prob"] = ft_probs
    test_df.to_csv(os.path.join(args.out, "test_predictions.csv"), index=False)

    print_comparison(results)
    print(f"\nFine-tuning took {train_seconds / 60:.1f} minutes.")
    print(f"Saved results.json, test_predictions.csv and lora_adapter/ in '{args.out}/'")


if __name__ == "__main__":
    main()
